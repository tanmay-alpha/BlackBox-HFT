//! Dataset identity, provenance and quality.

use serde::{Deserialize, Serialize};

use crate::{RelNs, time::TimeUnit};

/// Static description of the traded instrument.
#[derive(Copy, Clone, Debug, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
pub struct InstrumentMeta {
    /// Minimum price increment in quote currency.
    pub tick_size: f64,
    /// Minimum quantity increment in base units.
    pub lot_size: f64,
    /// Quote-currency value of `1.0` quantity at price `1.0` (1 for linear contracts).
    pub contract_size: f64,
}

impl InstrumentMeta {
    #[inline]
    pub fn price(&self, tick: i64) -> f64 {
        tick as f64 * self.tick_size
    }

    /// Nearest tick to `price`. Mirrors the engine: `(price / tick_size).round()`.
    #[inline]
    pub fn tick(&self, price: f64) -> i64 {
        (price / self.tick_size).round() as i64
    }

    /// Whole number of lots nearest to `qty`.
    #[inline]
    pub fn lots(&self, qty: f64) -> i64 {
        (qty / self.lot_size).round() as i64
    }
}

#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[serde(rename_all = "snake_case")]
pub enum DatasetKind {
    /// Generated by BlackBox from a seed. Not market data.
    Synthetic,
    /// Converted from recorded exchange data.
    Recorded,
}

/// Where the local receipt timestamps came from. Decides whether feed latency may be presented as
/// measured.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[serde(rename_all = "snake_case")]
pub enum LocalTsProvenance {
    /// Recorded by the capturing host. Feed latency is a measurement *at that host's location*,
    /// which is generally not where a user's strategy would run.
    Measured,
    /// Produced by the synthetic generator from a configured latency.
    Synthetic,
    /// The source had no receipt timestamps; they were set to `exch_ts + assumed latency`. Feed
    /// latency is an assumption, not an observation.
    Assumed,
}

/// Level of market data the dataset actually contains. Never overstated.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[serde(rename_all = "snake_case")]
pub enum DataLevel {
    /// Incremental Market-By-Price depth plus trades. Individual orders are not visible.
    L2MbpWithTrades,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
pub struct SourceInfo {
    /// Vendor or generator name, e.g. `"tardis.dev"` or `"blackbox-synthetic"`.
    pub vendor: String,
    pub exchange: String,
    pub symbol: String,
    /// Original files or URLs this dataset was built from, with their hashes.
    pub inputs: Vec<InputFile>,
    /// Redistribution and licensing note shown with the dataset.
    pub license_note: String,
    /// What the exchange timestamp means for this source (e.g. which exchange field it is).
    pub exch_ts_semantics: String,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
pub struct InputFile {
    /// File name or URL as supplied.
    pub name: String,
    /// `"trades"` or `"incremental_book_l2"` or `"synthetic"`.
    pub role: String,
    pub bytes: u64,
    /// SHA-256 of the file exactly as read (compressed bytes for `.gz`).
    pub sha256: String,
    pub rows: u64,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
pub struct TimestampInfo {
    /// Unit the source file declared or was told to use.
    pub input_unit: TimeUnit,
    pub local_ts: LocalTsProvenance,
    /// Constant added to all local timestamps during conversion because the source contained
    /// events whose local time preceded their exchange time (clock skew). Zero when none was
    /// needed. Mirrors the reference converter's `correct_local_timestamp`.
    #[cfg_attr(feature = "openapi", schema(value_type = String))]
    pub local_ts_shift_ns: i64,
    pub note: String,
}

#[derive(Copy, Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
pub struct EventCounts {
    /// Rows in the engine event array (a source row whose exchange and local order differ is
    /// split into two rows, so this can exceed the sum of the others).
    pub rows: u64,
    pub trades: u64,
    pub depth_updates: u64,
    pub snapshot_levels: u64,
    pub snapshots: u64,
    pub depth_clears: u64,
}

/// Severity of a data-quality finding.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[serde(rename_all = "snake_case")]
pub enum Severity {
    Info,
    Warn,
    /// The dataset should not be trusted for the affected interval.
    Error,
}

/// One data-quality check and its outcome.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
pub struct QualityCheck {
    /// Stable identifier, e.g. `"depth.crossed_book"`.
    pub id: String,
    pub title: String,
    pub severity: Severity,
    /// `true` when no occurrence was found.
    pub passed: bool,
    /// Number of occurrences.
    pub count: u64,
    pub detail: String,
    /// Up to a handful of concrete occurrences (source row numbers, timestamps, values).
    pub examples: Vec<String>,
}

#[derive(Copy, Clone, Debug, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
pub struct Quantiles {
    pub n: u64,
    pub min: f64,
    pub p50: f64,
    pub p90: f64,
    pub p99: f64,
    pub max: f64,
    pub mean: f64,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
pub struct QualityReport {
    pub checks: Vec<QualityCheck>,
    /// `local_ts - exch_ts` over all source rows after any shift.
    pub feed_latency_ns: Option<Quantiles>,
    /// Best ask minus best bid in ticks, sampled at every top-of-book change on the exchange clock.
    pub spread_ticks: Option<Quantiles>,
    /// Gap between consecutive exchange-clock events.
    pub inter_event_gap_ns: Option<Quantiles>,
    /// Fraction of the dataset's exchange-clock span during which the reconstructed book had both
    /// sides and was not crossed.
    pub book_valid_fraction: f64,
}

impl QualityReport {
    /// Worst severity among failed checks.
    pub fn worst(&self) -> Option<Severity> {
        let rank = |s: Severity| match s {
            Severity::Info => 0,
            Severity::Warn => 1,
            Severity::Error => 2,
        };
        self.checks
            .iter()
            .filter(|c| !c.passed)
            .map(|c| c.severity)
            .max_by_key(|s| rank(*s))
    }
}

/// Persisted next to the event file as `dataset.json`.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
pub struct DatasetManifest {
    pub contract_version: u32,
    /// Directory name; `[a-z0-9_-]+`.
    pub id: String,
    pub title: String,
    pub kind: DatasetKind,
    pub level: DataLevel,
    pub source: SourceInfo,
    pub instrument: InstrumentMeta,
    /// Absolute epoch nanoseconds of the dataset origin (its first exchange timestamp), as a
    /// decimal string. All `RelNs` values for this dataset are relative to it.
    pub origin_ns: String,
    /// First and last exchange-clock timestamps.
    #[cfg_attr(feature = "openapi", schema(value_type = String))]
    pub start: RelNs,
    #[cfg_attr(feature = "openapi", schema(value_type = String))]
    pub end: RelNs,
    pub timestamps: TimestampInfo,
    pub counts: EventCounts,
    /// File name of the engine event array inside the dataset directory.
    pub events_file: String,
    /// SHA-256 of that file. This is the dataset hash recorded in run manifests.
    pub events_sha256: String,
    pub events_bytes: u64,
    /// For synthetic datasets, the exact generator configuration (so it can be regenerated).
    pub generator: Option<serde_json::Value>,
    pub quality: QualityReport,
}

impl DatasetManifest {
    /// Parses `origin_ns`.
    pub fn origin(&self) -> Option<i64> {
        self.origin_ns.parse().ok()
    }
}
