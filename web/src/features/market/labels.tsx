// Labels shared by the workbench steps: the data-class badge and the check-status pill. Both carry
// text, never colour alone.

import { Badge, Pill } from '../../components/ui';
import type { CheckStatus } from './model';

/** The data-class badge; its wrapper lets the long label wrap on narrow screens. */
export function DataClassBadge({ dataClass }: { dataClass: string }) {
  return (
    <span className="mk-class">
      {dataClass === 'synthetic' ? (
        <Badge kind="warn" title="Generated by BlackBox from a fixed specification. Not market data; redistributable.">
          synthetic {'\u2014'} generated, not market data
        </Badge>
      ) : (
        <Badge kind="neutral" title="Private local data: never hosted, committed or served publicly.">
          private-local {'\u2014'} {dataClass}
        </Badge>
      )}
    </span>
  );
}

const STATUS: Record<CheckStatus, { tone: 'ok' | 'warn' | 'error' | 'info'; text: string }> = {
  pass: { tone: 'ok', text: 'pass' },
  warn: { tone: 'warn', text: 'warn' },
  fail: { tone: 'error', text: 'fail' },
  info: { tone: 'info', text: 'note' },
};

export function CheckPill({ status }: { status: CheckStatus }) {
  return <Pill tone={STATUS[status].tone}>{STATUS[status].text}</Pill>;
}
