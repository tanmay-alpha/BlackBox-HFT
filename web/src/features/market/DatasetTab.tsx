// Step 1, Dataset: what the source is, where it comes from and what it contains.

import { DataTable, type Column } from '../../components/DataTable';
import { JsonBlock } from '../../components/data';
import { fmtDuration, fmtInt } from '../../components/fmt';
import { HashText, Notice, Panel } from '../../components/ui';
import type { MarketSummary } from './api';
import { DataClassBadge } from './labels';
import { fmtSessionNs, fmtShare, nsBetween, typeCountRows, type TypeCountRow } from './model';

const TYPE_COLUMNS: Column<TypeCountRow>[] = [
  { id: 'type', header: 'Type', rowHeader: true, width: 64, cell: (r) => <span className="mono">{r.type}</span>, sortValue: (r) => r.type },
  { id: 'name', header: 'Message', cell: (r) => r.name, sortValue: (r) => r.name },
  { id: 'count', header: 'Messages', unit: 'count', numeric: true, cell: (r) => fmtInt(r.count), sortValue: (r) => r.count },
  { id: 'share', header: 'Share', unit: '%', numeric: true, cell: (r) => fmtShare(r.share), sortValue: (r) => r.share },
];

export function DatasetTab({ summary }: { summary: MarketSummary }) {
  const rows = typeCountRows(summary.messages_by_type);
  const total = rows.reduce((s, r) => s + r.count, 0);
  const span = nsBetween(summary.first_ns, summary.last_ns);
  return (
    <div className="mk-scroll">
      <div className="col mk-stack">
        <Panel title="Source" basis="observed" caption="As recorded in the workbench artifact. Source data here means present in the message stream.">
          <dl className="kv">
            <dt>Data class</dt>
            <dd>
              <DataClassBadge dataClass={summary.data_class} />
            </dd>
            <dt>Instrument</dt>
            <dd className="mono">{summary.symbol}</dd>
            <dt>Venue</dt>
            <dd>{summary.venue}</dd>
            <dt>Session</dt>
            <dd>{summary.session}</dd>
            <dt>Timestamp basis</dt>
            <dd>{summary.timestamp_basis}</dd>
            <dt>Dataset version</dt>
            <dd>
              <HashText hash={summary.dataset_version} chars={16} /> <span className="dim">(SHA-256 of the source bytes)</span>
            </dd>
            <dt>Events</dt>
            <dd className="mono">
              {fmtInt(summary.events)} <span className="dim">source frames, index 0 to {fmtInt(Math.max(0, summary.events - 1))}</span>
            </dd>
            <dt>First timestamp</dt>
            <dd className="mono">{fmtSessionNs(summary.first_ns)}</dd>
            <dt>Last timestamp</dt>
            <dd className="mono">{fmtSessionNs(summary.last_ns)}</dd>
            <dt>Span</dt>
            <dd className="mono">{span === null ? '\u2014' : fmtDuration(span)}</dd>
          </dl>
        </Panel>
        <Notice tag="Licensing" tone="info">
          {summary.license_note}
        </Notice>
        {summary.data_class === 'synthetic' ? (
          <Notice tag="Synthetic">
            Every message was generated by BlackBox from a fixed specification. Nothing on these pages is recorded market data,
            and no result here says anything about a real market.
          </Notice>
        ) : null}
        <Panel
          title="Messages by type"
          basis="observed"
          flush
          caption={`${fmtInt(total)} messages, counted by the decoder over the source. Letters are ITCH 5.0 message types.`}
        >
          <DataTable label="Messages by type" columns={TYPE_COLUMNS} rows={rows} rowKey={(r) => r.type} empty="The source holds no messages." />
        </Panel>
        <Panel title="Generator" caption="The generator specification exactly as the server sent it.">
          <JsonBlock summary="Show the generator specification" value={summary.generator} />
        </Panel>
      </div>
    </div>
  );
}
