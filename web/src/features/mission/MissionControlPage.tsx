function DatasetsSummary({ datasets }: { datasets: DatasetManifest[] }) {
  if (datasets.length === 0) {
    return (
      <Empty>
        No datasets are registered on the server. Ingest one with the <span className="mono">blackbox</span>{' '}
        CLI, then reload.
      </Empty>
    );
  }
  return (
    <div className="table-scroll">
      <table className="table">
        <thead>
          <tr>
            <th scope="col">Dataset</th>
            <th scope="col">Kind</th>
            <th scope="col">Source</th>
            <th scope="col" className="num">
              Span
            </th>
            <th scope="col" className="num">
              Rows
            </th>
            <th scope="col">Quality</th>
            <th scope="col">Open</th>
          </tr>
        </thead>
        <tbody>
          {datasets.map((ds) => {
            const worst = worstFailed(ds.quality);
            const failed = ds.quality.checks.filter((c) => !c.passed).length;
            return (
              <tr key={ds.id}>
                <th scope="row" className="wrap">
                  {ds.title}
                  <div className="mono dim small">{ds.id}</div>
                </th>
                <td>
                  {ds.kind === 'synthetic' ? (
                    <Badge kind="warn" title="Generated by BlackBox from a seed. This is not market data.">
                      synthetic
                    </Badge>
                  ) : (
                    <Badge kind="observed" title="Recorded historical market data.">
                      recorded
                    </Badge>
                  )}
                </td>
                <td className="mono small">
                  {ds.source.vendor} · {ds.source.exchange} · {ds.source.symbol}
                </td>
                <td className="num">{fmtDuration(ds.end - ds.start)}</td>
                <td className="num">{fmtInt(ds.counts.rows)}</td>
                <td>
                  {worst === null ? (
                    <Badge kind="ok">{ds.quality.checks.length} checks passed</Badge>
                  ) : (
                    <Badge kind={severityBadge(worst)}>
                      worst failed: {worst} ({failed} of {ds.quality.checks.length})
                    </Badge>
                  )}
                </td>
                <td className="nowrap">
                  <Link to={`/replay/${encodeURIComponent(ds.id)}`}>Replay</Link>
                  {' · '}
                  <Link to={`/lab?dataset=${encodeURIComponent(ds.id)}`}>Lab</Link>
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}

interface DemoProgress {
  demoId: string;
  done: number;
  total: number;
}

function DemoCard({
  demo,
  busy,
  progress,
  onRun,
}: {
  demo: Demo;
  busy: boolean;
  progress: DemoProgress | null;
  onRun: () => void;
}) {
  const running = progress !== null && progress.demoId === demo.id;
  return (
    <article className="mc-demo">
      <header className="col mc-demo-head">
        <h3>{demo.title}</h3>
        <p className="mc-question">{demo.question}</p>
      </header>
      <dl className="kv">
        <dt>Varied</dt>
        <dd>
          {demo.varied.length === 0 ? (
            <span className="dim">nothing</span>
          ) : (
            <ul className="mc-list">
              {demo.varied.map((v) => (
                <li key={v}>{v}</li>
              ))}
            </ul>
          )}
        </dd>
        <dt>Controlled</dt>
        <dd className="prose">
          <details>
            <summary>{demo.controlled.length} settings held identical</summary>
            <ul className="mc-list mc-controlled">
              {demo.controlled.map((c) => (
                <li key={c}>{c}</li>
              ))}
            </ul>
          </details>
        </dd>
        <dt>Runs</dt>
        <dd className="prose">
          <ol className="mc-list">
            {demo.runs.map((r, i) => (
              <li key={i}>
                {r.label}
                {i === 0 ? <span className="dim"> (baseline)</span> : null}
              </li>
            ))}
          </ol>
        </dd>
      </dl>
      <p className="note">{demo.how_to_read}</p>
      <details>
        <summary>Reproduce from the command line ({demo.reproduce.length} commands)</summary>
        {demo.reproduce.map((cmd, i) => (
          <pre key={i} className="mc-pre">
            {cmd}
          </pre>
        ))}
      </details>
      <div className="row mc-demo-actions">
        <button type="button" className="btn-primary" onClick={onRun} disabled={busy}>
          Run demo
        </button>
        {running ? (
          <Spinner
            label={`Simulating run ${Math.min(progress.done + 1, progress.total)} of ${progress.total} (stored runs return immediately)`}
          />
        ) : (
          <span className="dim small">
            Runs {demo.runs.length} simulations, or returns the stored ones, then opens the Latency
            Lab.
          </span>
        )}
      </div>
    </article>
  );
}

function Demos({ datasets }: { datasets: DatasetManifest[] }) {
  const navigate = useNavigate();
  const [datasetId, setDatasetId] = useState('');
  const demos = useAsync(() => api.demos(datasetId || undefined), [datasetId]);
  const [progress, setProgress] = useState<DemoProgress | null>(null);
  const [runError, setRunError] = useState<unknown>(null);

  const runDemo = async (demo: Demo) => {
    setRunError(null);
    setProgress({ demoId: demo.id, done: 0, total: demo.runs.length });
    const ids: string[] = [];
    try {
      // Sequential: the server runs each simulation synchronously; one at a time keeps the
      // progress honest and avoids competing simulations.
      for (const [i, r] of demo.runs.entries()) {
        const summary = await api.createRun({ config: r.config, label: `${demo.title}: ${r.label}` });
        ids.push(summary.manifest.run_id);
        setProgress({ demoId: demo.id, done: i + 1, total: demo.runs.length });
      }
    } catch (e) {
      setRunError(e);
      setProgress(null);
      return;
    }
    setProgress(null);
    navigate(`/latency?runs=${ids.map(encodeURIComponent).join(',')}&demo=${encodeURIComponent(demo.id)}`);
  };

  return (
    <Panel
      title="Canonical experiments"
      actions={
        datasets.length > 1 ? (
          <>
            <label htmlFor="mc-demo-dataset">Dataset</label>
            <select
              id="mc-demo-dataset"
              value={datasetId}
              onChange={(e) => setDatasetId(e.target.value)}
              disabled={progress !== null}
            >
              <option value="">server default ({datasets[0].id})</option>
              {datasets.map((d) => (
                <option key={d.id} value={d.id}>
                  {d.id}
                </option>
              ))}
            </select>
          </>
        ) : null
      }
    >
      <div className="col">
        <p className="note">
          Each experiment is a set of run configurations on one dataset that differ only in the
          listed variables. Runs are content-addressed: running a demo again returns the same run
          ids and results.
        </p>
        {runError ? <ErrorBox error={runError} /> : null}
        {demos.loading && !demos.data ? <Spinner label="Loading experiments" /> : null}
        {demos.error ? <ErrorBox error={demos.error} /> : null}
        {demos.data && demos.data.length === 0 ? (
          <Empty>The server offers no experiments for this dataset.</Empty>
        ) : null}
        {demos.data && demos.data.length > 0 ? (
          <div className="mc-demos">
            {demos.data.map((demo) => (
              <DemoCard
                key={demo.id}
                demo={demo}
                busy={progress !== null}
                progress={progress}
                onRun={() => void runDemo(demo)}
              />
            ))}
          </div>
        ) : null}
      </div>
    </Panel>
  );
}

