// Prototype A of the public latency experiment: a chart-first replay of the stored `cost_of_latency`
// demo. The URL holds the view (`view`), the replay time (`t`, ns after the dataset origin) and
// the inspected order (`order`), so leaving for forensics and coming back keeps the context.

import { memo, useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { Link, useSearchParams } from 'react-router-dom';

import type { InstrumentMeta, OrderPair } from '../../../api/types';
import { ErrorBox, Spinner, useAsync, useElapsedSeconds } from '../../../components/ui';
import { paths } from '../../../shell/paths';
import { divergences, loadMoment, momentWindow, type LatencyStory, type Moment } from '../story';
import { Assumptions } from './Assumptions';
import { Inspector } from './Inspector';
import { Ladder } from './Ladder';
import { PriceChart } from './PriceChart';
import { Results } from './Results';
