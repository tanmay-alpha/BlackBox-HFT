// The model assumptions and limitations of the experiment, from the published demo, the stored
// comparison's interpretation notes and the dataset manifest. Technical identifiers last.

import type { DatasetManifest } from '../../../api/types';
import { fmtDuration, fmtDurationExact, humanizeNsText } from '../../../components/fmt';
import { BasisBadge } from '../../../components/ui';
import type { LatencyStory } from '../story';
import type { Which } from './data';

export function Assumptions({ story, manifest, labels }: { story: LatencyStory; manifest: DatasetManifest; labels: Record<Which, string> }) {
  const notes = story.comparison?.interpretation ?? [];
  return (
    <details className="pa-details pa-assumptions" id="assumptions">
      <summary>Model assumptions and limitations</summary>
      <div className="pa-assumptions-body">
        <section>
          <h3>What differs between the scenarios</h3>
          <table className="pa-table">
            <thead>
              <tr>
                <th scope="col">Setting</th>
                <th scope="col">{labels.fast} scenario</th>
                <th scope="col">{labels.slow} scenario</th>
              </tr>
            </thead>
            <tbody>
              <tr>
                <th scope="row">Order latency, strategy → exchange (modeled)</th>
                <td className="pa-num">{fmtDurationExact(story.fast.entryNs)}</td>
                <td className="pa-num">{fmtDurationExact(story.slow.entryNs)}</td>
              </tr>
              <tr>
                <th scope="row">Response latency, exchange → strategy (modeled)</th>
                <td className="pa-num">{fmtDurationExact(story.fast.responseNs)}</td>
                <td className="pa-num">{fmtDurationExact(story.slow.responseNs)}</td>
              </tr>
            </tbody>
          </table>
        </section>
        <section>
          <h3>Held identical in both</h3>
          <ul>
            {story.demo.controlled.map((c) => (
              <li key={c}>{c}</li>
            ))}
          </ul>
        </section>
        <section>
          <h3>The data</h3>
          <p>
            {manifest.kind === 'synthetic' ? (
              <>
                <strong>Synthetic dataset</strong> (“{manifest.title}”): generated by BlackBox from a seed, not recorded market data.
              </>
            ) : (
              <>Recorded dataset “{manifest.title}”.</>
            )}{' '}
            It covers {fmtDuration(manifest.end - manifest.start)} of level-2 book updates and trades.
          </p>
          {manifest.timestamps.note ? <p>{manifest.timestamps.note}</p> : null}
        </section>
        <section>
          <h3>How to read the result</h3>
          <p>{story.demo.how_to_read}</p>
          <ul className="pa-notes">
            {notes.map((n) => (
              <li key={n.statement}>
                <BasisBadge basis={n.basis} /> {humanizeNsText(n.statement)}
              </li>
            ))}
          </ul>
        </section>
        <details className="pa-details">
          <summary>Technical identifiers</summary>
          <dl className="pa-ids">
            <dt>{labels.fast} run</dt>
            <dd className="pa-num">{story.fast.runId}</dd>
            <dt>{labels.slow} run</dt>
            <dd className="pa-num">{story.slow.runId}</dd>
            <dt>Stored comparison</dt>
            <dd className="pa-num">{story.comparisonId ?? 'none'}</dd>
            <dt>Dataset</dt>
            <dd className="pa-num">
              {manifest.id} v{story.fast.run.dataset.version}
            </dd>
            <dt>Dataset events SHA-256</dt>
            <dd className="pa-num pa-break">{manifest.events_sha256}</dd>
            <dt>Reproduce</dt>
            <dd>
              <ul className="pa-num">
                {story.demo.reproduce.map((c) => (
                  <li key={c} className="pa-break">
                    {c}
                  </li>
                ))}
              </ul>
            </dd>
          </dl>
        </details>
      </div>
    </details>
  );
}
